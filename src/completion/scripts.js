// Shell integration scripts. They are small and delegate all logic to "mesh __complete".

export const zsh = () => `# MeshCLI completion for zsh (generated by "mesh completion zsh")
(( $+functions[compdef] )) || { autoload -Uz compinit && compinit -i; }
_meshcli_complete() {
  local -a out
  out=("\${(@f)$(command \${words[1]} __complete $((CURRENT - 1)) "\${(@)words[2,-1]}" 2>/dev/null)}")
  if [[ "\${out[1]}" == ":files" ]]; then _files; return; fi
  (( \${#out} )) && [[ -n "\${out[1]}" ]] && compadd -U -- "\${out[@]}"
}
compdef _meshcli_complete mesh meshcli
`;

export const bash = () => `# MeshCLI completion for bash (generated by "mesh completion bash")
_meshcli_complete() {
  local cur="\${COMP_WORDS[COMP_CWORD]}" line
  local IFS=$'\\n'
  local -a out=($(command "\${COMP_WORDS[0]}" __complete "$COMP_CWORD" "\${COMP_WORDS[@]:1}" 2>/dev/null))
  COMPREPLY=()
  if [[ "\${out[0]}" == ":files" ]]; then
    compopt -o filenames 2>/dev/null
    COMPREPLY=($(compgen -f -- "$cur"))
    return
  fi
  for line in "\${out[@]}"; do COMPREPLY+=("$(printf '%q' "$line")"); done
}
complete -F _meshcli_complete mesh meshcli
`;

export const fish = () => `# MeshCLI completion for fish (generated by "mesh completion fish")
function __meshcli_complete
    set -l tokens (commandline -opc)
    set -l cur (commandline -ct)
    set -l out (command $tokens[1] __complete (count $tokens) $tokens[2..-1] $cur 2>/dev/null)
    if test "$out[1]" = ":files"
        __fish_complete_path $cur
    else
        printf '%s\\n' $out
    end
end
complete -c mesh -f -a '(__meshcli_complete)'
complete -c meshcli -f -a '(__meshcli_complete)'
`;

export const powershell = () => `# MeshCLI completion for PowerShell (generated by "mesh completion powershell")
Register-ArgumentCompleter -Native -CommandName mesh, meshcli -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $elements = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })
    $words = @($elements | Select-Object -Skip 1)
    if ($wordToComplete -eq '') { $words += '' }
    $index = $words.Count
    $out = @(& $elements[0] __complete $index @words 2>$null)
    if ($out.Count -gt 0 -and $out[0] -eq ':files') { return }
    foreach ($item in $out) {
        if (-not $item) { continue }
        $text = if ($item -match '[\\s''"$\`;&|(){}]') { "'" + ($item -replace "'", "''") + "'" } else { $item }
        [System.Management.Automation.CompletionResult]::new($text, $item, 'ParameterValue', $item)
    }
}
`;

export const SCRIPTS = { zsh, bash, fish, powershell };
